var interfacePattern = regexp.MustCompile(`^[A-Za-z0-9_.:-]{1,32}$`)

func runCmd(name string, args ...string) (string, error) {
	output, err := exec.Command(name, args...).CombinedOutput()
	return strings.TrimSpace(string(output)), err
}

func applyPassword(username, password string) error {
	if _, err := runCmd("id", "-u", username); err != nil {
		return fmt.Errorf("user %s not found", username)
	}
	cmd := exec.Command("chpasswd")
	cmd.Stdin = strings.NewReader(username + ":" + password + "\n")
	if output, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("chpasswd failed: %v: %s", err, strings.TrimSpace(string(output)))
	}
	_, _ = runCmd("usermod", "-U", username)
	_, _ = runCmd("chage", "-M", "99999", username)
	_, _ = runCmd("chage", "-I", "-1", username)
	return nil
}

func defaultInterface() (string, error) {
	if output, err := runCmd("ip", "-4", "route", "show", "default"); err == nil {
		fields := strings.Fields(output)
		for index, field := range fields {
			if field == "dev" && index+1 < len(fields) {
				return fields[index+1], nil
			}
		}
	}
	output, err := runCmd("ip", "-o", "link", "show", "up")
	if err != nil {
		return "", fmt.Errorf("detect network interface: %v", err)
	}
	for _, line := range strings.Split(output, "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		name := strings.TrimSuffix(fields[1], ":")
		if name == "lo" || strings.HasPrefix(name, "veth") || strings.HasPrefix(name, "docker") {
			continue
		}
		return name, nil
	}
	return "", errors.New("no available network interface")
}

func applyDNS(dns1 string, dns2 string) error {
	servers := []string{}
	for _, server := range []string{strings.TrimSpace(dns1), strings.TrimSpace(dns2)} {
		if server != "" {
			servers = append(servers, server)
		}
	}
	if len(servers) == 0 {
		return errors.New("dns is required")
	}
	content := ""
	for _, server := range servers {
		content += "nameserver " + server + "\n"
	}
	return os.WriteFile("/etc/resolv.conf", []byte(content), 0o644)
}

func configureNetwork(ip string, prefix int, gateway string, dns1 string, dns2 string) error {
	iface, err := defaultInterface()
	if err != nil {
		return err
	}
	if !interfacePattern.MatchString(iface) {
		return fmt.Errorf("invalid interface name: %s", iface)
	}

	dnsServers := []string{}
	for _, server := range []string{strings.TrimSpace(dns1), strings.TrimSpace(dns2)} {
		if server != "" {
			dnsServers = append(dnsServers, server)
		}
	}
	if len(dnsServers) == 0 {
		dnsServers = append(dnsServers, gateway)
	}
	dnsYAML := ""
	for _, server := range dnsServers {
		dnsYAML += "          - " + server + "\n"
	}
	resolvConf := ""
	for _, server := range dnsServers {
		resolvConf += "nameserver " + server + "\n"
	}

	netplan := fmt.Sprintf(`# Generated by deviy-guest-agent
network:
  version: 2
  ethernets:
    %s:
      dhcp4: false
      dhcp6: false
      addresses:
        - %s/%d
      routes:
        - to: 0.0.0.0/0
          via: %s
      nameservers:
        addresses:
%s`, iface, ip, prefix, gateway, dnsYAML)

	netplanPath := "/etc/netplan/99-deviy-static.yaml"
	writeErr := os.WriteFile(netplanPath, []byte(netplan), 0o600)
	if writeErr == nil {
		if _, err := runCmd("netplan", "apply"); err == nil {
			return nil
		}
		// Keep the netplan file for the next boot, then fall back to live changes.
	}

	if _, err := runCmd("ip", "addr", "flush", "dev", iface, "scope", "global"); err != nil {
		return fmt.Errorf("flush address on %s: %v", iface, err)
	}
	if _, err := runCmd("ip", "addr", "add", fmt.Sprintf("%s/%d", ip, prefix), "dev", iface); err != nil {
		return fmt.Errorf("set address on %s: %v", iface, err)
	}
	if _, err := runCmd("ip", "route", "replace", "default", "via", gateway, "dev", iface); err != nil {
		return fmt.Errorf("set default route: %v", err)
	}
	_ = os.WriteFile("/etc/resolv.conf", []byte(resolvConf), 0o644)
	return nil
}

func resizeSystemDisk() (string, error) {
	root, err := runCmd("findmnt", "-n", "-o", "SOURCE", "/")
	if err != nil || root == "" {
		return "", fmt.Errorf("find root device: %v", err)
	}
	fstype, _ := runCmd("findmnt", "-n", "-o", "FSTYPE", "/")
	disk, err := runCmd("lsblk", "-no", "PKNAME", root)
	if err != nil || disk == "" {
		return "", fmt.Errorf("root filesystem %s is not on a resizable disk", root)
	}
	part := strings.TrimPrefix(root, "/dev/"+disk)
	part = strings.TrimPrefix(part, "p")
	if _, err := strconv.Atoi(part); err != nil {
		return "", fmt.Errorf("cannot detect partition number for %s", root)
	}
	device := "/dev/" + disk
	output, growErr := runCmd("growpart", device, part)
	if growErr != nil && !strings.Contains(output, "NOCHANGE") {
		return "", fmt.Errorf("growpart %s %s: %v: %s", device, part, growErr, output)
	}
	switch fstype {
	case "ext4", "ext3", "ext2":
		if output, err := runCmd("resize2fs", root); err != nil {
			return "", fmt.Errorf("resize2fs %s: %v: %s", root, err, output)
		}
	case "xfs":
		if output, err := runCmd("xfs_growfs", "/"); err != nil {
			return "", fmt.Errorf("xfs_growfs: %v: %s", err, output)
		}
	default:
		return "", fmt.Errorf("unsupported root filesystem: %s", fstype)
	}
	return fmt.Sprintf("resized %s on %s partition %s", root, device, part), nil
}

func ensureDataDisks() (string, error) {
	root, _ := runCmd("findmnt", "-n", "-o", "SOURCE", "/")
	rootDisk, _ := runCmd("lsblk", "-no", "PKNAME", root)
	rootDisk = filepath.Base(strings.TrimSpace(rootDisk))

	output, err := runCmd("lsblk", "-dpno", "NAME,TYPE,SIZE")
	if err != nil {
		return "", fmt.Errorf("list disks: %v", err)
	}
	details := make([]string, 0, 2)
	for _, line := range strings.Split(output, "\n") {
		fields := strings.Fields(line)
		if len(fields) < 3 || fields[1] != "disk" {
			continue
		}
		device := fields[0]
		if filepath.Base(device) == rootDisk {
			continue
		}
		mounts, _ := runCmd("lsblk", "-no", "MOUNTPOINT", device)
		if strings.TrimSpace(mounts) != "" {
			details = append(details, fmt.Sprintf("skip %s: already mounted", device))
			continue
		}

		part := ""
		names, _ := runCmd("lsblk", "-ln", "-o", "NAME", device)
		for index, name := range strings.Split(names, "\n") {
			name = strings.TrimSpace(name)
			if index == 0 || name == "" {
				continue
			}
			part = "/dev/" + name
			break
		}
		if part == "" {
			if output, err := runCmd("parted", "-s", device, "mklabel", "gpt", "mkpart", "primary", "ext4", "0%", "100%"); err != nil {
				return "", fmt.Errorf("partition %s: %v: %s", device, err, output)
			}
			_, _ = runCmd("partprobe", device)
			time.Sleep(time.Second)
			names, _ = runCmd("lsblk", "-ln", "-o", "NAME", device)
			for index, name := range strings.Split(names, "\n") {
				name = strings.TrimSpace(name)
				if index == 0 || name == "" {
					continue
				}
				part = "/dev/" + name
				break
			}
		}
		if part == "" {
			return "", fmt.Errorf("cannot create partition on %s", device)
		}

		fstype, _ := runCmd("lsblk", "-no", "FSTYPE", part)
		fstype = strings.TrimSpace(fstype)
		if fstype == "" {
			if output, err := runCmd("mkfs.ext4", "-F", "-L", "DeviyData", part); err != nil {
				return "", fmt.Errorf("mkfs.ext4 %s: %v: %s", part, err, output)
			}
			fstype = "ext4"
		}
		if fstype != "ext4" && fstype != "xfs" {
			details = append(details, fmt.Sprintf("skip %s: unsupported filesystem %s", part, fstype))
			continue
		}
		if _, err := os.Stat("/data"); err != nil {
			if err := os.MkdirAll("/data", 0o755); err != nil {
				return "", fmt.Errorf("create /data: %v", err)
			}
		}
		if _, err := runCmd("mountpoint", "-q", "/data"); err != nil {
			if output, err := runCmd("mount", part, "/data"); err != nil {
				return "", fmt.Errorf("mount %s on /data: %v: %s", part, err, output)
			}
		}
		if uuid, err := runCmd("blkid", "-s", "UUID", "-o", "value", part); err == nil && uuid != "" {
			ensureFstab(uuid, fstype)
		}
		details = append(details, fmt.Sprintf("disk=%s part=%s fs=%s mount=/data", device, part, fstype))
	}
	return strings.Join(details, "\n"), nil
}

func ensureFstab(uuid, fstype string) {
	const fstab = "/etc/fstab"
	entry := fmt.Sprintf("UUID=%s /data %s defaults,nofail 0 2", uuid, fstype)
	data, err := os.ReadFile(fstab)
	if err != nil {
		return
	}
	if strings.Contains(string(data), "UUID="+uuid) {
		return
	}
	content := strings.TrimRight(string(data), "\n") + "\n" + entry + "\n"
	_ = os.WriteFile(fstab, []byte(content), 0o644)
}

func rebootSystem() error {
	go func() {
		time.Sleep(time.Second)
		_ = exec.Command("systemctl", "reboot").Run()
	}()
	return nil
}

func setHostname(name string) error {
	if output, err := runCmd("hostnamectl", "set-hostname", name); err != nil {
		if writeErr := os.WriteFile("/etc/hostname", []byte(name+"\n"), 0o644); writeErr != nil {
			return fmt.Errorf("set hostname: %v: %s", err, output)
		}
	}
	updateHosts(name)
	return nil
}

func updateHosts(name string) {
	const hosts = "/etc/hosts"
	data, err := os.ReadFile(hosts)
	if err != nil {
		return
	}
	lines := strings.Split(string(data), "\n")
	found := false
	for index, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "127.0.1.1") {
			lines[index] = "127.0.1.1 " + name
			found = true
		}
	}
	if !found {
		lines = append(lines, "127.0.1.1 "+name)
	}
	_ = os.WriteFile(hosts, []byte(strings.Join(lines, "\n")), 0o644)
}

